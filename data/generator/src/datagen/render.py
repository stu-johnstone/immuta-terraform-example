"""Turns a Script into SQL text for a platform, with comments that explain
each step, so the file can be read and pasted into a SQL editor."""

from __future__ import annotations

import textwrap
from dataclasses import dataclass

from .dialects import Dialect
from .model import Derived, Script, Sql, Table

RULE = "-- " + "=" * 76
SUBRULE = "-- " + "-" * 76

LAYERS = {
    "bronze": "Bronze: raw extracts from the source systems, loaded as-is.",
    "silver": "Silver: cleaned, typed and conformed. Built from bronze.",
    "gold": "Gold: business-ready data products for reporting and AI. Built from silver.",
}


@dataclass
class Block:
    """Either comment lines or one SQL statement."""

    text: str
    is_sql: bool


def comment(*paragraphs: str) -> Block:
    lines = []
    for paragraph in paragraphs:
        lines += textwrap.wrap(paragraph, 76) or [""]
    return Block("\n".join(f"-- {line}".rstrip() for line in lines), False)


def banner(title: str, *paragraphs: str, rule: str = RULE) -> Block:
    body = comment(title, *paragraphs).text
    return Block(f"{rule}\n{body}\n{rule}", False)


def describe_table(table: Table | Derived) -> Block:
    lines = [f"{table.name}: {table.comment}"]
    block = comment(*lines).text
    if isinstance(table, Table):
        noted = [c for c in table.columns if c.comment]
        if noted:
            block += "\n--   Columns of note:"
            for c in noted:
                block += "\n" + "\n".join(
                    textwrap.wrap(f"{c.name}: {c.comment}", 76, initial_indent="--     ", subsequent_indent="--       ")
                )
        block += f"\n--   Rows: {len(table.rows)}"
    return Block(block, False)


def blocks(script: Script, dialect: Dialect) -> list[Block]:
    out = [
        banner(
            f"{script.title} - {dialect.title}",
            script.description,
            "Generated by data/generator (make data). Run the whole file top to bottom; "
            "it can be re-run and replaces the tables each time.",
            "Dates are relative to the day the script runs, so 'today' and 'this month' "
            "always have data. All people, companies and identifiers are fictional.",
        )
    ]
    notes, setup = dialect.setup(script)
    out.append(banner("Setup", *notes, rule=SUBRULE))
    out += [Block(s, True) for s in setup]

    created: dict[str, str] = {}
    for schema in script.schemas:

        def ref(name: str, schema_name: str = schema.name) -> str:
            key = name if "." in name else f"{schema_name}.{name}"
            if key not in created:
                raise KeyError(f"{key} is referenced before it is created")
            return created[key]

        location = dialect.table(script.container, schema.name, "")[:-1]
        out.append(banner(f"{schema.title} ({location})", schema.description))

        out.append(banner(LAYERS["bronze"], rule=SUBRULE))
        for table in schema.bronze:
            name = dialect.table(script.container, schema.name, table.name)
            out.append(describe_table(table))
            out += [Block(s, True) for s in dialect.create_table(name, table) + dialect.insert(name, table)]
            created[f"{schema.name}.{table.name}"] = name

        for layer in ("silver", "gold"):
            derived = getattr(schema, layer)
            if not derived:
                continue
            out.append(banner(LAYERS[layer], rule=SUBRULE))
            for table in derived:
                name = dialect.table(script.container, schema.name, table.name)
                select = table.select(Sql(dialect, ref))
                out.append(describe_table(table))
                out += [Block(s, True) for s in dialect.create_table_as(name, table.comment, select)]
                created[f"{schema.name}.{table.name}"] = name
    return out


def render(script: Script, dialect: Dialect) -> str:
    return "\n\n".join(b.text for b in blocks(script, dialect)) + "\n"


def statements(script: Script, dialect: Dialect) -> list[str]:
    return [b.text for b in blocks(script, dialect) if b.is_sql]
